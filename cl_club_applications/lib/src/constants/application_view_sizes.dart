/// Sizes of the Applications views (club_client#321).
abstract final class ApplicationViewSizes {
  /// Padding around a page.
  static const double pagePadding = 24;

  /// Widest a page's column grows.
  static const double maxContentWidth = 960;

  /// Gap between a page's sections.
  static const double sectionGap = 20;

  /// Gap between rows of a list.
  static const double rowGap = 8;

  /// Gap between small items.
  static const double smallGap = 8;

  /// A button's spinner.
  static const double spinner = 14;

  /// Widest a refusal under a download button grows.
  static const double refusalWidth = 320;

  /// Widest an inline section form grows.
  static const double editMaxWidth = 720;

  /// Width of a read line's label.
  static const double readLabelWidth = 160;

  /// Widest the create dialog grows.
  static const double dialogWidth = 480;

  /// Padding inside a list row.
  static const double rowPadding = 12;

  /// Gap between a greyed-out move and its reason.
  static const double reasonGap = 6;

  /// The width of the Facts help (club_client#389).
  static const double helpWidth = 360;

  /// The size of the Facts help's (?) icon.
  static const double helpIcon = 18;
}
