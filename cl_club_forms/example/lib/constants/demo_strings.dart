/// The words the demo shows around the forms.
abstract final class DemoStrings {
  /// The app's name, wherever a person sees one. `web/index.html` and
  /// `web/manifest.json` carry the same name; a test keeps them in step.
  static const String appName = 'Club Forms';

  /// Under the app's name in the sidebar.
  static const String sidebarSubtitle = 'A preview of every form';

  /// Tooltip of the light / dark toggle.
  static const String toggleTheme = 'Toggle light / dark';

  /// Label of the top bar's button that validates the form shown.
  static const String validate = 'Validate';

  /// Label of the top bar's button that mounts the form shown afresh.
  static const String reset = 'Reset';

  /// Tooltip of the button that opens the sidebar on a narrow window.
  static const String openSidebar = 'Forms';
}
