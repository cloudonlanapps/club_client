/// Sizes of the rows of `EventStaffForm`.
abstract final class EventStaffFormLayout {
  /// Radius of the avatar that leads a member's line.
  static const double avatarRadius = 14;

  /// Size of the initials inside the avatar.
  static const double avatarFontSize = 11;

  /// Size of the username under a member's name.
  static const double usernameFontSize = 11;

  /// Size of an action's icon.
  static const double iconSize = 16;

  /// Between the parts of one row: avatar, text and action.
  static const double inlineGap = 8;
}
