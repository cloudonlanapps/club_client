/// Sizes of the submit-documents step.
abstract final class IdentityDocumentsSubmitSizes {
  /// Widest the step grows on a wide screen.
  static const double maxWidth = 480;

  /// Padding at the step's sides.
  static const double sidePadding = 16;

  /// Padding above and below the step.
  static const double endPadding = 24;

  /// Gap between the intro, the upload cards and the buttons' reason.
  static const double gap = 16;

  /// Gap between the upload cards and the consent, and above the help.
  static const double sectionGap = 24;

  /// Gap between the two buttons.
  static const double buttonGap = 8;

  /// Padding above and below the help section's points.
  static const double tipsPadding = 4;

  /// Gap between two of the help section's points.
  static const double tipGap = 2;

  /// Widest the privacy policy's text grows.
  static const double policyMaxWidth = 480;

  /// Gap between two paragraphs of the privacy policy.
  static const double policyParagraphGap = 12;
}
