/// Sizes of the reapply view.
abstract final class ReapplySizes {
  /// Widest the view's column grows on a wide screen.
  static const double maxWidth = 480;

  /// Left and right of the column.
  static const double horizontalPadding = 16;

  /// Above and below the column.
  static const double verticalPadding = 24;

  /// Between the heading and the line under it.
  static const double headingGap = 4;

  /// Between the heading block and the admin's note.
  static const double noteGap = 16;

  /// Above the form, and between the form and its action.
  static const double sectionGap = 20;

  /// Inside the admin's note.
  static const double notePadding = 12;

  /// Corner radius of the admin's note.
  static const double noteRadius = 8;
}
